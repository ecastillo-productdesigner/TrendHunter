"""Build the followed-collection feed from actual prototype collection/story pages."""
from pathlib import Path
import html, json, re, hashlib
from collection_momentum import momentum_markup
site = Path(__file__).resolve().parents[1] / 'site'
source = (site / 'collection-data.js').read_text()
collections = json.loads(re.search(r'Object.freeze\((\[.*?\])\.map', source, re.S)[1])
manifest = json.loads((site / 'assets/authors/manifest.json').read_text())
names = {author['id']: author['name'] for author in manifest['authors']}
names['samantha-agate'] = 'Samantha Agate'
names['ryan-brennan'] = 'Ryan Brennan'
manifest['stories']['trend-maximalism.html'] = 'ryan-brennan'
manifest['stories']['trend.html'] = 'samantha-agate'
feed = (site / 'feed.html').read_text()
originals = re.findall(r'<article class="trend-card trend-card--editorial"[^>]*>.*?</article>', feed, re.S)
by_href = {re.search(r'data-href="([^"]+)"', card)[1]: card for card in originals}
membership = {}
for collection in collections:
    page = (site / collection['href']).read_text()
    section = re.search(r'<section class="collection-trends".*?</section>', page, re.S)
    if section:
        for href in dict.fromkeys(re.findall(r'href="(trend[^\"]*\.html)"', section[0])):
            membership.setdefault(href, []).append(collection['href'])
for page in site.glob('trend*.html'):
    content = page.read_text()
    primary = re.search(r'<a href="([^"]+)" class="article-collection"', content)
    if primary and primary[1] in {c['href'] for c in collections}:
        groups = membership.setdefault(page.name, [])
        if primary[1] not in groups: groups.append(primary[1])
stories = []
for href, groups in membership.items():
    content = by_href.get(href, (site / href).read_text())
    button = re.search(r'<button[^>]*class="[^"]*bookmark-button[^>]*>', content)
    if not button: continue
    attrs = dict(re.findall(r'(data-[\w-]+)="([^"]*)"', button[0]))
    author = manifest['stories'].get(href)
    if not author:
        byline = re.search(r'<(?:a|p)[^>]*class="contributor-byline"[^>]*>.*?</(?:a|p)>', (site / href).read_text(), re.S)
        if byline:
            link = re.search(r'href="([^"]+)"', byline[0])
            if link: author = link[1].removeprefix('contributor-').removesuffix('.html')
    if not author or author not in names: continue
    stories.append({'href':href, 'id':html.unescape(attrs['data-story']), 'title':html.unescape(attrs['data-title']), 'image':attrs['data-image'], 'authorId':author, 'author':names[author], 'collections':groups, **({'authorHref':'contributor.html', 'authorImage':'assets/contributor/samantha-agate.png'} if author == 'samantha-agate' else {'authorImage':'assets/trend/byline-ryan-brennan.png'} if author == 'ryan-brennan' else {})})
(site / 'collection-story-data.js').write_text('// Generated by scripts/build-collection-story-data.py from the existing collection and article pages.\nexport const COLLECTION_STORIES = ' + json.dumps(stories, ensure_ascii=False, indent=2) + ';\n')
# Digest excerpts come from the existing article copy, never invented publication
# events or generated claims. Revisions change only when that story's copy changes.
digest = {}
for story in stories:
    page = (site / story['href']).read_text()
    context = re.search(r'<section class="context-card".*?</section>', page, re.S)
    body = re.search(r'<div class="article-body"[^>]*>(.*)', page, re.S)
    paragraphs = re.findall(r'<p(?:\s[^>]*)?>(.*?)</p>', (body[1] if body else '') + (context[0] if context else ''), re.S)
    sentences = []
    for paragraph in paragraphs:
        text = re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', '', paragraph))).strip()
        if not text or text in sentences: continue
        for sentence in re.split(r'(?<=[.!?])\s+(?=[A-Z“])', text):
            if sentence not in sentences: sentences.append(sentence)
            if len(sentences) >= 2: break
        if len(sentences) >= 2: break
    summary = ' '.join(sentences)
    assert summary, f'Missing digest excerpt: {story["href"]}'
    revision = hashlib.sha256((story['title'] + summary).encode()).hexdigest()[:16]
    digest[story['href']] = {'summary':summary, 'revision':revision}
(site / 'hunter-digest-data.js').write_text('// Generated from existing prototype article excerpts. Fictional sample coverage; no live publication feed.\nexport const DIGEST_EXCERPTS = ' + json.dumps(digest, ensure_ascii=False, indent=2) + ';\n')
# The detail list and followed feed share the same complete membership set.
# Retain existing secondary memberships, then include each article's primary collection.
for collection in collections:
    path = site / collection['href']
    page = path.read_text()
    # Collection identity stays free of chevrons. The inline summary shares the
    # catalog's fixed illustrative score and recency with What’s Changing.
    masthead = re.search(r'<header class="masthead">.*?</header>', page, re.S)
    assert masthead, f'Missing collection masthead: {path.name}'
    description = re.search(r'<p class="masthead-description">.*?</p>', masthead[0], re.S)
    assert description, f'Missing collection description: {path.name}'
    hours = collection['hours']
    signed = ('−' if collection['direction'] == 'falling' else '+') + str(collection['percentage']) + '%'
    header = f'''<header class="masthead">
          <div class="masthead-title-row"><h1 class="masthead-title">{html.escape(collection['name'])}</h1></div>
          {description[0]}
          <div class="collection-interest-bar">
            <div class="collection-interest-summary" data-direction="{collection['direction']}" role="group" aria-label="Seven-day interest change · prototype sample" title="Illustrative interest change compared with the previous 7 days. Prototype sample, not live analytics.">
              <div class="collection-interest-signal"><strong class="collection-interest-value">{signed}</strong>{momentum_markup(collection['direction'], collection['href'], value=collection['percentage'])}</div>
              <p class="collection-interest-metadata"><span class="collection-interest-updated">Updated {hours}hr{'s' if hours != 1 else ''} ago</span><span class="collection-interest-separator" aria-hidden="true"> · </span><span class="collection-interest-period">Interest · 7 days</span></p>
            </div>
            <div class="masthead-actions">
              <button class="follow-button" type="button" data-collection-follow="{collection['href']}" aria-pressed="false">Follow</button>
              <button class="article-share" type="button" aria-label="Share collection"><span class="article-share-icon" aria-hidden="true"></span></button>
            </div>
          </div>
        </header>'''
    page = page[:masthead.start()] + header + page[masthead.end():]
    rows = ''.join(
        f'<li><a href="{story["href"]}" class="story-lockup"><img class="story-lockup-image" src="{story["image"]}" alt="" loading="lazy"><h3 class="story-lockup-headline">{html.escape(story["title"])}</h3></a></li>'
        for story in stories if collection['href'] in story['collections']
    )
    page, count = re.subn(
        r'(<section class="collection-trends".*?<ul class="story-list">).*?(</ul>\s*</section>)',
        lambda match: match[1] + rows + match[2], page, flags=re.S,
    )
    assert count == 1, f'Missing collection story list: {path.name}'
    path.write_text(page)
print(f'Built {len(stories)} stories across {len(collections)} collection memberships')
